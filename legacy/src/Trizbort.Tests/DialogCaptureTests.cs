  // ---- Capture machinery ----

  private void Guarded(string name, Action action)
  {
    _currentDialog = name;
    var before = _written.Count;
    // Exceptions thrown inside the WinForms message loop (e.g. a dialog's Load handler) would otherwise pop up the
    // "unhandled exception" dialog and block the run; record them as failures instead.
    ThreadExceptionEventHandler onThreadException = (_, args) =>
      _failures.Add(name + ": " + args.Exception.GetType().Name + " in message loop: " + args.Exception.Message);
    Application.ThreadException += onThreadException;
    try
    {
      action();
    }
    catch (Exception exception)
    {
      _failures.Add(name + ": " + exception.GetType().Name + ": " + exception.Message);
    }
    finally
    {
      Application.ThreadException -= onThreadException;
    }

    if (_written.Count == before) _failures.Add(name + ": no images written");
    Assert.Pass();
  }

  private static void CaptureForm(Form form, string dialog)
  {
    try
    {
      form.StartPosition = FormStartPosition.Manual;
      form.ShowInTaskbar = false;
      form.Location = new Point(-3000, -3000);
      form.Show();
      form.Location = new Point(-3000, -3000);
      Application.DoEvents();

      var tabs = AllControls(form).OfType<TabControl>().FirstOrDefault();
      if (tabs == null)
      {
        CapturePage(form, form, dialog, "main");
      }
      else
      {
        foreach (var page in tabs.TabPages.Cast<TabPage>().ToList())
        {
          tabs.SelectedTab = page;
          Application.DoEvents();
          CapturePage(form, page, dialog, page.Text);
        }
      }
    }
    finally
    {
      try
      {
        form.Close();
      }
      catch (Exception exception)
      {
        _failures.Add(dialog + ": close threw " + exception.GetType().Name);
      }

      form.Dispose();
    }
  }

  private static void CapturePage(Form form, Control scope, string dialog, string tab)
  {
    Save(form, dialog, tab, "default");

    var toggles = AllControls(scope)
                  .Where(c => (c is CheckBox || c is RadioButton) && c.Visible && c.Enabled)
                  .Cast<ButtonBase>()
                  .ToList();
    foreach (var toggle in toggles)
    {
      var radio = toggle as RadioButton;
      var check = toggle as CheckBox;
      if (radio != null && radio.Checked) continue; // already the selected radio; its siblings cover the other state

      var siblings = toggle.Parent == null
        ? new List<RadioButton>()
        : toggle.Parent.Controls.OfType<RadioButton>().ToList();
      var siblingStates = siblings.ToDictionary(s => s, s => s.Checked);
      var wasChecked = check != null && check.Checked;
      var before = AllControls(form).ToDictionary(c => c, c => c.Enabled);
      try
      {
        if (check != null) check.Checked = !wasChecked;
        else radio.Checked = true;
        Application.DoEvents();

        var changed = AllControls(form).Any(c => c != toggle && before.TryGetValue(c, out var was) && was != c.Enabled);
        if (changed)
        {
          var isOn = check != null ? check.Checked : radio.Checked;
          var name = string.IsNullOrEmpty(toggle.Name) ? toggle.Text : toggle.Name;
          Save(form, dialog, tab, Sanitise(name) + (isOn ? "-on" : "-off"), false);
        }
      }
      catch (Exception exception)
      {
        _failures.Add(dialog + "/" + tab + "/" + toggle.Name + ": toggle threw " + exception.GetType().Name);
      }
      finally
      {
        // Restore the original state (and re-run the dialog's enable logic).
        if (check != null) check.Checked = wasChecked;
        foreach (var sibling in siblingStates.Where(s => s.Value)) sibling.Key.Checked = true;
        Application.DoEvents();
      }
    }
  }

  private static void Save(Form form, string dialog, string tab, string state, bool sanitiseState = true)
  {
    var file = Sanitise(dialog) + "__" + Sanitise(tab) + "__" + (sanitiseState ? Sanitise(state) : state) + ".png";
    using var bitmap = new Bitmap(form.Width, form.Height);
    form.DrawToBitmap(bitmap, new Rectangle(0, 0, form.Width, form.Height));
    bitmap.Save(Path.Combine(_output, file), ImageFormat.Png);
    _written.Add(file);
  }

  private static string Sanitise(string text)
  {
    var clean = Regex.Replace(text ?? string.Empty, "[^A-Za-z0-9-]+", "-").Trim('-');
    return clean.Length == 0 ? "unnamed" : clean;
  }

  private static IEnumerable<Control> AllControls(Control root)
  {
    foreach (Control child in root.Controls)
    {
      yield return child;
      foreach (var descendant in AllControls(child)) yield return descendant;
    }
  }

  /// <summary>
  ///   Replaces the real dialog/message-box plumbing: instead of blocking modally, the form passed to
  ///   UserInteraction.ShowDialog is handed to the capture callback and Cancel is returned.
  /// </summary>
  private sealed class CapturingInteraction(Action<Form> capture) : IUserInteraction
  {
    public DialogResult ShowMessage(
      IWin32Window owner,
      string text,
      string caption,
      MessageBoxButtons buttons,
      MessageBoxIcon icon,
      MessageBoxDefaultButton defaultButton)
    {
      _failures.Add("message box suppressed: " + caption + ": " + text);
      return DialogResult.Cancel;
    }

    public DialogResult ShowDialog(Form dialog, IWin32Window owner)
    {
      capture(dialog);
      return DialogResult.Cancel;
    }

    public DialogResult ShowDialog(CommonDialog dialog, IWin32Window owner)
    {
      return DialogResult.Cancel;
    }

    public string GetClipboardText()
    {
      return string.Empty;
    }

    public void SetClipboardText(string text, TextDataFormat format)
    {
    }
  }
