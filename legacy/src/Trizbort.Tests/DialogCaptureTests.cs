/// <summary>
///   Reference-screenshot harness for the Avalonia parity review (task T0.4).
///   Skipped unless the TRIZBORT_CAPTURE_OUTPUT environment variable names an output folder, so the normal test
///   run is unaffected. Run on Windows with e.g.
///   <c>TRIZBORT_CAPTURE_OUTPUT=C:\shots dotnet test --filter DialogCaptureTests</c>.
///
///   Fixture: tests/manual/object-testing.trizbort (linked as Fixtures/Manual) - it has rooms with objects, a
///   connection and regions. No manual fixture contains a label element, so a MapLabel is created in code.
///
///   Every dialog is shown non-modally off-screen (Location -3000,-3000, not in taskbar), then each TabPage is
///   selected and captured with Control.DrawToBitmap as <c>Dialog__tab__default.png</c>. For every CheckBox/RadioButton
///   on a page whose toggling changes the Enabled state of any other control, the toggled state is captured as
///   <c>Dialog__tab__controlName-on.png</c> / <c>-off.png</c> (detected automatically, so it also covers
///   Door/Open/Lockable, Automap verbose transcript, Settings margins, App settings tooltip limits, room corners,
///   label outline/background).
///
///   Known limitations (listed in index.md when they occur):
///   - Only the first TabControl in a dialog is walked; nested TabControls are not.
///   - Dependent states are only explored one control at a time (no combinations).
///   - Dependent states driven by non-check controls (list selection in DisambiguateRoomsDialog, region delete button
///     in SettingsDialog) are not captured.
///   - MapStatisticsView needs Project.Current.Canvas (a running MainForm); it is attempted and, if it throws, the
///     failure is recorded in index.md instead of failing the test.
///   - OnlineHelpDialog, AboutDialog etc. have no tabs, so one "main" image each.
/// </summary>
[TestFixture]
[Apartment(ApartmentState.STA)]
[NonParallelizable]
[Category("Manual")]
