{
  private const string OutputVariable = "TRIZBORT_CAPTURE_OUTPUT";

  private static readonly List<string> _written = new();
  private static readonly List<string> _failures = new();
  private static string _output;

  private string _currentDialog;
  private RoomPropertiesDialog.Tab _previousTab;

  [OneTimeSetUp]
  public void RequireOutputFolder()
  {
    _output = Environment.GetEnvironmentVariable(OutputVariable);
    if (string.IsNullOrWhiteSpace(_output))
      Assert.Ignore(OutputVariable + " is not set; dialog capture skipped.");
    Directory.CreateDirectory(_output);
    _written.Clear();
    _failures.Clear();
  }

  [OneTimeTearDown]
  public void WriteIndex()
  {
    if (string.IsNullOrWhiteSpace(_output)) return;
    var text = new StringBuilder();
    text.AppendLine("# WinForms dialog captures");
    text.AppendLine();
    text.AppendLine("Source: tests/manual/object-testing.trizbort. Generated by DialogCaptureTests (T0.4).");
    text.AppendLine();
    text.AppendLine("## Files (" + _written.Count + ")");
    text.AppendLine();
    foreach (var file in _written.OrderBy(name => name, StringComparer.Ordinal)) text.AppendLine("- " + file);
    text.AppendLine();
    text.AppendLine("## Not captured / failures (" + _failures.Count + ")");
    text.AppendLine();
    if (_failures.Count == 0) text.AppendLine("- none");
    foreach (var failure in _failures) text.AppendLine("- " + failure);
    File.WriteAllText(Path.Combine(_output, "index.md"), text.ToString());
  }

